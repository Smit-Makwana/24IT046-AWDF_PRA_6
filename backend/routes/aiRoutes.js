// backend/routes/aiRoutes.js
// Practical 13: AI API Integration with Graceful Degradation & Fallbacks

const express = require("express");
const router = express.Router();

// Simple in-memory rate limiting map: ip -> lastRequestTimestamp
const rateLimitMap = new Map();
const RATE_LIMIT_MS = 5000; // 1 request per 5 seconds per client to prevent spam/cost overflow

// Fallback generator for smart graceful degradation
function getFallbackDescription(title, category) {
  const cat = category || "general";
  return `Organized session focused on "${title.trim()}". Participants will collaborate, discuss core topics in ${cat}, and coordinate action items. (Generated by offline fallback)`;
}

router.post("/generate-description", async (req, res) => {
  try {
    const { title, category } = req.body;

    if (!title || !title.trim()) {
      return res.status(400).json({
        success: false,
        message: "Title is required for AI generation",
      });
    }

    // 1. Rate limiting check (Supplementary Problem: Rate Limiting)
    const clientIp = req.ip || req.headers["x-forwarded-for"] || "default-client";
    const now = Date.now();
    const lastRequest = rateLimitMap.get(clientIp);

    if (lastRequest && now - lastRequest < RATE_LIMIT_MS) {
      const waitSec = Math.ceil((RATE_LIMIT_MS - (now - lastRequest)) / 1000);
      return res.status(429).json({
        success: false,
        message: `Please wait ${waitSec}s before generating again.`,
        fallback: false,
      });
    }
    rateLimitMap.set(clientIp, now);

    const apiKey = process.env.OPENAI_API_KEY;
    const geminiKey = process.env.GEMINI_API_KEY;

    // 2. Check if OpenAI API key is configured
    if (apiKey && apiKey !== "your_openai_api_key_here") {
      try {
        const OpenAI = require("openai");
        const client = new OpenAI({ apiKey });

        const prompt = `Write a short, engaging, and professional event/task description (maximum 3 sentences) for: "${title}". Category: ${category || "General"}.`;

        const completion = await client.chat.completions.create({
          model: "gpt-4o-mini",
          messages: [{ role: "user", content: prompt }],
          max_tokens: 120,
        });

        const generatedText = completion.choices[0]?.message?.content?.trim();
        if (generatedText) {
          return res.status(200).json({
            success: true,
            description: generatedText,
            source: "openai",
            fallback: false,
          });
        }
      } catch (openAiError) {
        console.warn("OpenAI API call failed or quota exceeded:", openAiError.message);
        // Do not throw: continue down to Gemini or graceful fallback
      }
    }

    // 3. Check if Gemini API key is configured as alternate
    if (geminiKey && geminiKey !== "your_gemini_api_key_here") {
      try {
        const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiKey}`;
        const geminiRes = await fetch(geminiUrl, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [
              {
                parts: [
                  {
                    text: `Write a short professional description (under 50 words) for event title: "${title}".`,
                  },
                ],
              },
            ],
          }),
        });

        if (geminiRes.ok) {
          const geminiData = await geminiRes.json();
          const text = geminiData.candidates?.[0]?.content?.parts?.[0]?.text?.trim();
          if (text) {
            return res.status(200).json({
              success: true,
              description: text,
              source: "gemini",
              fallback: false,
            });
          }
        }
      } catch (geminiError) {
        console.warn("Gemini API call failed:", geminiError.message);
      }
    }

    // 4. Graceful Degradation: If no API key or remote service fails/times out, return smart template
    console.log("Using graceful degradation fallback for AI description.");
    return res.status(200).json({
      success: true,
      description: getFallbackDescription(title, category),
      source: "fallback",
      fallback: true,
      notice: "Remote AI service unavailable or unconfigured. Provided template-based suggestion.",
    });

  } catch (error) {
    // 5. Uncaught exception safeguard: App NEVER crashes
    console.error("Critical error in /api/ai/generate-description:", error);
    return res.status(200).json({
      success: true,
      description: getFallbackDescription(req.body?.title || "Task", req.body?.category),
      source: "fallback",
      fallback: true,
    });
  }
});

module.exports = router;
